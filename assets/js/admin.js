        function formatMoneySA(val) {
            var str = (val + '').replace(/\D/g, '');
            if (!str) return '0';
            var lastThree = str.substring(str.length - 3);
            var rest = str.substring(0, str.length - 3);
            if (rest !== '') {
                lastThree = ',' + lastThree;
                rest = rest.replace(/\B(?=(\d{2})+(?!\d))/g, ',');
            }
            return rest + lastThree;
        }

