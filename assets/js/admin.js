    function money(raw) {
        var digits = String(Math.abs(parseInt(raw, 10) || 0));
        if (digits.length > 3) {
            var tail = digits.slice(-3);
            var head = digits.slice(0, -3).replace(/\B(?=(\d{2})+(?!\d))/g, ',');
            digits = head + ',' + tail;
        }
        return '৳' + digits;
    }

