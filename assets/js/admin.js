    function animateCount(el) {
        if (el.__counted) {
            return;
        }
        el.__counted = true;

        var target = parseFloat(el.getAttribute('data-pk-count') || el.getAttribute('data-count') || '0');
        var isMoney = el.hasAttribute('data-pk-money') || el.hasAttribute('data-money');
        var suffix = el.getAttribute('data-pk-suffix') || el.getAttribute('data-suffix') || '';
        var startTs = null;
        var duration = 900;

        function step(ts) {
            startTs = startTs || ts;
            var progress = Math.min(1, (ts - startTs) / duration);
            var eased = 1 - Math.pow(1 - progress, 3);
            var currentVal = Math.round(target * eased);

            el.textContent = (isMoney ? money(currentVal) : currentVal) + suffix;

            if (progress < 1) {
                requestAnimationFrame(step);
            } else {
                el.textContent = (isMoney ? money(target) : target) + suffix;
            }
        }

        requestAnimationFrame(step);
    }

    function initMeters() {
        document.querySelectorAll('.meter i[data-pk-w], .meter i[data-w], .pk-meter i[data-pk-w], .pk-meter i[data-w]').forEach(function (i) {
            var width = i.getAttribute('data-pk-w') || i.getAttribute('data-w') || '0';
            i.style.width = width + '%';
        });
    }

    function initCounts() {
        if ('IntersectionObserver' in window) {
            var observer = new IntersectionObserver(function (entries) {
                entries.forEach(function (entry) {
                    if (entry.isIntersecting) {
                        animateCount(entry.target);
                        observer.unobserve(entry.target);
                    }
                });
            }, { threshold: 0.1 });

            document.querySelectorAll('[data-pk-count], [data-count]').forEach(function (el) {
                observer.observe(el);
            });
        } else {
            document.querySelectorAll('[data-pk-count], [data-count]').forEach(function (el) {
                animateCount(el);
            });
        }

        setTimeout(initMeters, 60);
    }

