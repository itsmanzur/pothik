    function getToastContainer() {
        var container = document.getElementById('toasts') || document.querySelector('.pk-toasts');
        if (!container) {
            container = document.createElement('div');
            container.id = 'toasts';
            container.className = 'pk-toasts toasts';
            container.setAttribute('aria-live', 'polite');
            document.body.appendChild(container);
        }
        return container;
    }

    function toast(msg, undo) {
        if (!msg) {
            return;
        }
        var container = getToastContainer();
        var t = document.createElement('div');
        t.className = 'pk-toast toast';
        t.setAttribute('role', 'alert');

        var iconSpan = document.createElement('span');
        iconSpan.className = 't-ico';
        iconSpan.innerHTML = '<svg class="i sm" aria-hidden="true"><use href="#i-check"/></svg>';

        var textSpan = document.createElement('span');
        textSpan.textContent = msg;

        t.appendChild(iconSpan);
        t.appendChild(textSpan);

        if (typeof undo === 'function') {
            var b = document.createElement('button');
            b.type = 'button';
            b.textContent = i18n.undo || 'Undo';
            b.onclick = function () {
                undo();
                t.remove();
            };
            t.appendChild(b);
        }

        container.appendChild(t);
        var timer = setTimeout(function () {
            if (t.parentNode) {
                t.style.transition = 'opacity 0.25s, transform 0.25s';
                t.style.opacity = '0';
                t.style.transform = 'translateY(8px)';
                setTimeout(function () {
                    t.remove();
                }, 260);
            }
        }, 3600);

        t.addEventListener('mouseenter', function () {
            clearTimeout(timer);
        });
        t.addEventListener('mouseleave', function () {
            timer = setTimeout(function () {
                if (t.parentNode) {
                    t.remove();
                }
            }, 1800);
        });
    }

    config.toast = toast;

