    function markFormDirty(form) {
        if (!dirtyForms.has(form)) {
            dirtyForms.add(form);
            var savebar = document.getElementById('savebar') || form.querySelector('.pk-savebar') || document.querySelector('.pk-savebar');
            if (savebar) {
                savebar.classList.add('show');
            }
        }
    }

    function clearFormDirty(form) {
        dirtyForms.delete(form);
        var savebar = document.getElementById('savebar') || document.querySelector('.pk-savebar');
        if (savebar && dirtyForms.size === 0) {
            savebar.classList.remove('show');
        }
    }

    window.addEventListener('beforeunload', function (e) {
        if (dirtyForms.size > 0) {
            var msg = i18n.unsavedChanges || 'You have unsaved changes.';
            e.returnValue = msg;
            return msg;
        }
    });

    // Ctrl/Cmd + S shortcut on dirty forms
    document.addEventListener('keydown', function (e) {
        var k = e.key ? e.key.toLowerCase() : '';
        if ((e.ctrlKey || e.metaKey) && k === 's') {
            if (dirtyForms.size > 0) {
                e.preventDefault();
                var first = dirtyForms.values().next().value;
                if (first) {
                    clearFormDirty(first);
                    first.submit();
                }
            }
        }
    });

    document.addEventListener('click', function (e) {
        var discard = e.target.closest('[data-pk-discard], #discard');
        if (discard) {
            e.preventDefault();
            dirtyForms.clear();
            var savebar = document.getElementById('savebar') || document.querySelector('.pk-savebar');
            if (savebar) {
                savebar.classList.remove('show');
            }
            window.location.reload();
        }
    });

