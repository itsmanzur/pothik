    function ensureCmdkElements() {
        cmdkBg = document.getElementById('cmdk') || document.querySelector('.pk-cmdk-bg');
        if (cmdkBg) {
            cmdkIn = cmdkBg.querySelector('#cmdkIn');
            cmdkList = cmdkBg.querySelector('#cmdkList');
        }
    }

    function renderCmdkList() {
        if (!cmdkList) {
            return;
        }
        var query = (cmdkIn && cmdkIn.value ? cmdkIn.value : '').toLowerCase().trim();

        var filtered = DEFAULT_COMMANDS.filter(function (c) {
            return !query || c.l.toLowerCase().indexOf(query) !== -1;
        });

        cmdkItems = filtered.concat(cmdkRemotePilgrims || []);
        if (cmdkIndex >= cmdkItems.length) {
            cmdkIndex = Math.max(0, cmdkItems.length - 1);
        }

        var currentGroup = '';
        var html = '';

        if (!cmdkItems.length) {
            cmdkList.innerHTML = '<li class="grp">' + (i18n.noResults || 'No results') + '</li>';
            return;
        }

        cmdkItems.forEach(function (it, idx) {
            if (it.g !== currentGroup) {
                currentGroup = it.g;
                html += '<li class="grp">' + escapeHtml(currentGroup) + '</li>';
            }
            var isAct = (idx === cmdkIndex) ? ' act' : '';
            var iconHtml = it.isPilgrim
                ? '<svg class="i sm"><use href="#i-users"/></svg>'
                : (it.g === (i18n.actions || 'Actions')
                    ? '<svg class="i sm"><use href="#i-spark"/></svg>'
                    : '<svg class="i sm"><use href="#i-arrow"/></svg>');

            html += '<li data-ci="' + idx + '" class="' + isAct + '">' +
                iconHtml +
                '<span>' + escapeHtml(it.l) + '</span>' +
                (idx === cmdkIndex ? '<small>↵</small>' : '') +
                '</li>';
        });

        cmdkList.innerHTML = html;
    }

    var cmdkRemotePilgrims = [];

    function fetchPilgrims(query) {
        if (!config.ajax || !config.nonce || query.length < 2) {
            cmdkRemotePilgrims = [];
            renderCmdkList();
            return;
        }

        var url = config.ajax + '?action=pothik_search_inquiries&nonce=' + encodeURIComponent(config.nonce) + '&q=' + encodeURIComponent(query);
        fetch(url)
            .then(function (res) { return res.json(); })
            .then(function (json) {
                if (json && json.success && Array.isArray(json.data)) {
                    cmdkRemotePilgrims = json.data.map(function (p) {
                        return {
                            g: i18n.pilgrims || 'Pilgrims',
                            l: p.name + ' · ' + p.phone + (p.city ? ' · ' + p.city : ''),
                            url: p.url,
                            isPilgrim: true
                        };
                    });
                } else {
                    cmdkRemotePilgrims = [];
                }
                renderCmdkList();
            })
            .catch(function () {
                cmdkRemotePilgrims = [];
                renderCmdkList();
            });
    }

    function openCmdk() {
        ensureCmdkElements();
        if (!cmdkBg) {
            return;
        }
        lastActiveElement = document.activeElement;
        cmdkBg.hidden = false;
        cmdkRemotePilgrims = [];
        cmdkIndex = 0;
        if (cmdkIn) {
            cmdkIn.value = '';
            cmdkIn.focus();
        }
        renderCmdkList();
    }

    function closeCmdk() {
        if (cmdkBg) {
            cmdkBg.hidden = true;
        }
        if (lastActiveElement && typeof lastActiveElement.focus === 'function') {
            lastActiveElement.focus();
        }
    }

    function runCmdk(item) {
        if (!item) {
            return;
        }
        closeCmdk();

        if (item.url) {
            var target = softUrl(item.url);
            if (target) {
                softGo(target, true);
            } else {
                window.location.href = item.url;
            }
            return;
        }

        if (item.action === 'new_package') {
            var f1 = document.getElementById('pk-cmdk-new-pkg') || document.querySelector('form[action*="pothik_new_package"]');
            if (f1) {
                f1.submit();
            }
            return;
        }

        if (item.action === 'export_csv') {
            var f2 = document.getElementById('pk-cmdk-export-csv') || document.querySelector('form[action*="pothik_export_inquiries"]');
            if (f2) {
                f2.submit();
                toast(i18n.csvDownloaded || 'CSV export started');
            }
            return;
        }

        if (item.action === 'copy_catalog') {
            copyText('[pothik_catalog]').then(function () {
                toast(i18n.catalogCopied || 'Copied [pothik_catalog]');
            });
            return;
        }
    }

    document.addEventListener('click', function (e) {
        var trigger = e.target.closest('[data-pk-cmdk], [data-cmdk]');
        if (trigger) {
            e.preventDefault();
            openCmdk();
            return;
        }

        if (cmdkBg && !cmdkBg.hidden) {
            if (e.target === cmdkBg) {
                closeCmdk();
                return;
            }
            var li = e.target.closest('li[data-ci]');
            if (li) {
                var idx = parseInt(li.getAttribute('data-ci'), 10);
                if (cmdkItems[idx]) {
                    runCmdk(cmdkItems[idx]);
                }
            }
        }
    });

    document.addEventListener('keydown', function (e) {
        var k = e.key ? e.key.toLowerCase() : '';

        // Ctrl/Cmd + K
        if ((e.ctrlKey || e.metaKey) && k === 'k') {
            e.preventDefault();
            if (cmdkBg && !cmdkBg.hidden) {
                closeCmdk();
            } else {
                openCmdk();
            }
            return;
        }

        // Palette active key handlers
        if (cmdkBg && !cmdkBg.hidden) {
            if (k === 'escape') {
                e.preventDefault();
                closeCmdk();
                return;
            }
            if (k === 'arrowdown') {
                e.preventDefault();
                cmdkIndex = Math.min(cmdkItems.length - 1, cmdkIndex + 1);
                renderCmdkList();
                scrollCmdkActive();
                return;
            }
            if (k === 'arrowup') {
                e.preventDefault();
                cmdkIndex = Math.max(0, cmdkIndex - 1);
                renderCmdkList();
                scrollCmdkActive();
                return;
            }
            if (k === 'enter') {
                e.preventDefault();
                if (cmdkItems[cmdkIndex]) {
                    runCmdk(cmdkItems[cmdkIndex]);
                }
                return;
            }
        }
    });

    function scrollCmdkActive() {
        if (!cmdkList) {
            return;
        }
        var act = cmdkList.querySelector('li.act');
        if (act && typeof act.scrollIntoView === 'function') {
            act.scrollIntoView({ block: 'nearest' });
        }
    }

    document.addEventListener('input', function (e) {
        if (cmdkIn && e.target === cmdkIn) {
            cmdkIndex = 0;
            renderCmdkList();
            clearTimeout(searchTimer);
            var q = cmdkIn.value.trim();
            if (q.length >= 2) {
                searchTimer = setTimeout(function () {
                    fetchPilgrims(q);
                }, 250);
            } else {
                cmdkRemotePilgrims = [];
                renderCmdkList();
            }
        }
    });

